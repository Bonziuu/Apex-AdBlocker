// Rebuild the compact, shared MAIN-world helper from the vendored official PSL.
// Refresh tools/public-suffix-list.dat separately; this generator never uses the network.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function entityHelperSource(root = ROOT) {
  const source = fs.readFileSync(path.join(root, 'tools/public-suffix-list.dat'), 'utf8');
  const rules = source.split(/\r?\n/).map((s) => s.trim()).filter((s) => s && !s.startsWith('//')).map((s) => {
    const prefix = s.startsWith('!') ? '!' : s.startsWith('*.') ? '*.' : '';
    const host = prefix ? s.slice(prefix.length) : s;
    return prefix + new URL(`https://${host}/`).hostname;
  });
  const hash = crypto.createHash('sha256').update(source).digest('hex');
  return `/* Public Suffix List data: Mozilla Public License 2.0; see shared/public-suffix-LICENSE.txt.
 * Source: https://github.com/publicsuffix/list/blob/master/public_suffix_list.dat
 * Snapshot SHA-256: ${hash}
 * Generated by tools/build-entity-hosts.mjs. Includes ICANN and PRIVATE rules.
 */
(function () {
'use strict';
const key = Symbol.for('ApexAdBlocker.entityHostKeys.v1');
if (typeof globalThis[key] === 'function') return;
// Parse only on the first relevant hostname; repeat script registrations reuse
// this non-writable function. The rule set remains inside its closure.
const data = ${JSON.stringify(rules.join('\n'))};
let rules;
const resolve = (raw) => {
  const hostname = String(raw || '').toLowerCase().replace(/\\.$/, '');
  if (!hostname) return [];
  const labels = hostname.split('.');
  const out = labels.map((_, i) => labels.slice(i).join('.'));
  if (labels.length < 2 || /^(?:\\d+\\.){3}\\d+$/.test(hostname) || hostname.includes(':')) return out;
  if (!rules) rules = new Set(data.split('\\n'));
  let suffixLength = 1; // PSL's prevailing default rule '*', including new TLDs.
  for (let i = 0; i < labels.length; i++) {
    const suffix = labels.slice(i).join('.');
    const length = labels.length - i;
    if (rules.has('!' + suffix)) { suffixLength = length - 1; break; }
    if (rules.has(suffix)) suffixLength = Math.max(suffixLength, length);
    if (i > 0 && rules.has('*.' + suffix)) suffixLength = Math.max(suffixLength, length + 1);
  }
  const entity = labels.slice(0, -suffixLength);
  for (let i = 0; i < entity.length; i++) out.push(entity.slice(i).join('.') + '.*');
  return out;
};
Object.freeze(resolve);
Object.defineProperty(globalThis, key, { value: resolve, writable: false, configurable: false });
})();
`;
}
export function buildEntityHelper(root = ROOT) {
  const destination = path.join(root, 'shared/entity-hosts.js');
  fs.writeFileSync(destination, entityHelperSource(root));
  return destination;
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) buildEntityHelper();
